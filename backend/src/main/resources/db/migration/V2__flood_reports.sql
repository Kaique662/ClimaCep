-- Relatos de usuários sobre alagamento/ausência de alagamento por CEP.
-- Um relato por usuário e CEP; atualizações substituem o relato anterior.
CREATE TABLE flood_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  cep VARCHAR(8) NOT NULL,
  status VARCHAR(20) NOT NULL CHECK (status IN ('FLOODED', 'CLEAR')),
  note VARCHAR(280),
  neighborhood VARCHAR(120),
  city VARCHAR(120),
  state VARCHAR(2),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_flood_report_user_cep UNIQUE (user_id, cep)
);
CREATE INDEX idx_flood_reports_cep_recent ON flood_reports(cep, updated_at DESC);
CREATE INDEX idx_flood_reports_user_id ON flood_reports(user_id);
